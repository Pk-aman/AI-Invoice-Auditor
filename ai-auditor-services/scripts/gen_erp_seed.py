#!/usr/bin/env python3
"""Generate infra/postgres/init/03_erp_seed.sql from Raw Data/data/ERP_mockdata/*.json.

Validates referential integrity first and fails loudly on problems.
Usage: python ai-auditor-services/scripts/gen_erp_seed.py
"""
import json
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "Raw Data" / "data" / "ERP_mockdata"
OUT = ROOT / "infra" / "postgres" / "init" / "03_erp_seed.sql"


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, int | float | Decimal):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main() -> int:
    vendors = json.loads((SRC / "vendors.json").read_text(encoding="utf-8"))
    pos = json.loads((SRC / "PO Records.json").read_text(encoding="utf-8"))
    skus = json.loads((SRC / "sku_master.json").read_text(encoding="utf-8"))

    vendor_ids = {v["vendor_id"] for v in vendors}
    sku_codes = {s["item_code"] for s in skus}
    problems = []
    for po in pos:
        if po["vendor_id"] not in vendor_ids:
            problems.append(f"{po['po_number']}: unknown vendor {po['vendor_id']}")
        for li in po["line_items"]:
            if li["item_code"] not in sku_codes:
                problems.append(f"{po['po_number']}: item {li['item_code']} missing from sku_master")
    if problems:
        print("Referential problems in source data:", *problems, sep="\n  - ")
        print("(continuing: seed is still generated; ERP /sku will 404 for these items)")

    lines = ["-- GENERATED by ai-auditor-services/scripts/gen_erp_seed.py — do not edit by hand.", ""]
    for v in vendors:
        lines.append(
            "INSERT INTO erp.vendors (vendor_id, vendor_name, country, currency) VALUES "
            f"({q(v['vendor_id'])}, {q(v['vendor_name'])}, {q(v.get('country'))}, {q(v['currency'])}) ON CONFLICT DO NOTHING;"
        )
    lines.append("")
    for s in skus:
        lines.append(
            "INSERT INTO erp.sku_master (item_code, category, uom, gst_rate) VALUES "
            f"({q(s['item_code'])}, {q(s.get('category'))}, {q(s.get('uom'))}, {q(s.get('gst_rate'))}) ON CONFLICT DO NOTHING;"
        )
    lines.append("")
    for po in pos:
        lines.append(
            f"INSERT INTO erp.purchase_orders (po_number, vendor_id) VALUES ({q(po['po_number'])}, {q(po['vendor_id'])}) ON CONFLICT DO NOTHING;"
        )
        for n, li in enumerate(po["line_items"], start=1):
            lines.append(
                "INSERT INTO erp.po_line_items (po_number, line_number, item_code, description, qty, unit_price, currency) VALUES "
                f"({q(po['po_number'])}, {n}, {q(li['item_code'])}, {q(li.get('description'))}, {li['qty']}, {li['unit_price']}, {q(li['currency'])}) ON CONFLICT DO NOTHING;"
            )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    n_lines = sum(len(p["line_items"]) for p in pos)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(vendors)} vendors, {len(pos)} POs, {n_lines} PO lines, {len(skus)} SKUs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
